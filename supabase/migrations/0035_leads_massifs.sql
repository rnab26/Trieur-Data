create or replace function trieur_data.leads_exiger(p_ecriture boolean) returns void
language plpgsql stable security definer set search_path = trieur_data as $$
begin
    if p_ecriture then
        if not trieur_data.leads_peut_ecrire() then raise exception 'acces_refuse: ecriture Leads non autorisee'; end if;
    elsif not trieur_data.leads_peut_lire() then
        raise exception 'acces_refuse: lecture Leads non autorisee';
    end if;
end;
$$;

