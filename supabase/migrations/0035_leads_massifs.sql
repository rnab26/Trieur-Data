-- 0035 : base "Leads" pour des dizaines de millions de lignes. Chantier cockpit 6547bd6a.
--
-- POURQUOI UNE TABLE A PART : trieur_data.records garde chaque ligne en jsonb
-- (noms de colonnes répétés dans chaque ligne, ~3 fois plus gros) avec un index de
-- recherche par trigrammes (~1/3 de la table en plus) : mesuré pour 500 000 lignes,
-- inutilisable à 60 millions. Ici : colonnes typées, aucun index de recherche, la table
-- est découpée par département (une partition = un fichier physique) : exporter un
-- département = lire un fichier de bout en bout, sans index.
--
-- CETTE MIGRATION NE FAIT QU'AJOUTER (tables, fonctions) : rien n'est modifié ni supprimé,
-- idempotente. Aucune ligne n'est créée dans les tables existantes.
--
-- Choix de dédoublonnage (voir PROJECT_LOG.md) : clé = téléphone mobile, sinon fixe,
-- sinon e-mail, UNIQUE par (département, clé). Une ligne sans téléphone ni e-mail est
-- comptée "invalide" et n'est pas gardée.

