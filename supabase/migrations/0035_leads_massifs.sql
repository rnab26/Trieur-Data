create or replace function trieur_data.leads_dept(p_cp text) returns smallint
language sql immutable parallel safe as $$
    select case
        when c is null or length(c) < 4 then 0
        else (case
            when left(lpad(c, 5, '0'), 2) = '20' then (case when lpad(c, 5, '0') < '20200' then 201 else 202 end)
            when left(lpad(c, 5, '0'), 2) in ('97', '98') then left(lpad(c, 5, '0'), 3)::int
            when left(lpad(c, 5, '0'), 2)::int between 1 and 95 then left(lpad(c, 5, '0'), 2)::int
            else 0 end)
    end::smallint
    from (select regexp_replace(coalesce(p_cp, ''), '\D', '', 'g') as c) s;
$$;

create or replace function trieur_data.leads_tel(p_tel text) returns bigint
language sql immutable parallel safe as $$
    select case when length(d) >= 9 then right(d, 9)::bigint end
    from (select regexp_replace(coalesce(p_tel, ''), '\D', '', 'g') as d) s;
$$;

create or replace function trieur_data.leads_email(p_email text) returns text
language sql immutable parallel safe as $$
    select case when e like '%_@_%' then e end from (select lower(btrim(coalesce(p_email, ''))) as e) s;
$$;

create or replace function trieur_data.leads_cle(p_mobile text, p_fixe text, p_email text) returns bigint
language sql immutable parallel safe as $$
    select coalesce(
        trieur_data.leads_tel(p_mobile),
        trieur_data.leads_tel(p_fixe),
        case when trieur_data.leads_email(p_email) is not null
             then -((hashtextextended(trieur_data.leads_email(p_email), 0) & 4611686018427387903) + 1) end
    );
$$;

create or replace function trieur_data.leads_civilite(p text) returns smallint
language sql immutable parallel safe as $$
    select case
        when lower(btrim(coalesce(p, ''))) in ('m', 'm.', 'mr', 'monsieur', 'h', 'homme') then 1
        when lower(btrim(coalesce(p, ''))) in ('mme', 'madame', 'mlle', 'mademoiselle', 'f', 'femme', 'mme.') then 2
    end::smallint;
$$;

create or replace function trieur_data.leads_date(p text) returns date
language plpgsql immutable parallel safe as $$
begin
    if p ~ '^\d{4}-\d{2}-\d{2}' then
        return left(p, 10)::date;
    elsif p ~ '^\d{1,2}[/.-]\d{1,2}[/.-]\d{4}' then
        return to_date(substring(p from '^\d{1,2}[/.-]\d{1,2}[/.-]\d{4}'), 'DD/MM/YYYY');
    end if;
    return null;
exception when others then
    return null;
end;
$$;

create or replace function trieur_data.leads_partition(p_dept int) returns text
language sql immutable parallel safe as $$
    select case when p_dept between 1 and 95 and p_dept <> 20 or p_dept in (201, 202, 971, 972, 973, 974, 975, 976)
                then 'leads_p' || lpad(p_dept::text, 3, '0') else 'leads_p_autres' end;
$$;

-- "01".."95", "2A", "2B", "971".. pour l'écran
create or replace function trieur_data.leads_dept_libelle(p_dept int) returns text
language sql immutable parallel safe as $$
    select case when p_dept = 201 then '2A' when p_dept = 202 then '2B'
                when p_dept = 0 then 'Autres / inconnu' when p_dept >= 971 then p_dept::text
                else lpad(p_dept::text, 2, '0') end;
$$;

