create or replace function trieur_data.leads_reglage_poser(p_cle text, p_valeur text) returns void
language plpgsql security definer set search_path = trieur_data as $$
begin
    if not trieur_data.is_super_admin() then raise exception 'acces_refuse: reserve aux administrateurs'; end if;
    update trieur_data.leads_reglages set valeur = p_valeur where cle = p_cle;
    if not found then raise exception 'reglage_inconnu: %', p_cle; end if;
end;
$$;

create or replace function trieur_data.leads_source_obtenir(p_nom text) returns smallint
language plpgsql security definer set search_path = trieur_data as $$
declare v_id smallint;
begin
    perform trieur_data.leads_exiger(true);
    p_nom := btrim(coalesce(p_nom, ''));
    if p_nom = '' then raise exception 'source_vide: donne un nom de source'; end if;
    insert into trieur_data.leads_sources (nom) values (p_nom) on conflict (nom) do nothing;
    select id into v_id from trieur_data.leads_sources where nom = p_nom;
    return v_id;
end;
$$;

create or replace function trieur_data.leads_source_regler(p_id smallint, p_statut text, p_note text default null) returns void
language plpgsql security definer set search_path = trieur_data as $$
begin
    perform trieur_data.leads_exiger(true);
    if p_statut not in ('a_verifier', 'bonne', 'mauvaise') then raise exception 'statut_invalide: %', p_statut; end if;
    update trieur_data.leads_sources set statut = p_statut, note = coalesce(p_note, note) where id = p_id;
    if not found then raise exception 'source_inconnue: %', p_id; end if;
end;
$$;

-- Liste des sources avec le nombre de lignes encore en base (jamais un balayage de la table)
create or replace function trieur_data.leads_sources_lister() returns jsonb
language plpgsql stable security definer set search_path = trieur_data as $$
begin
    perform trieur_data.leads_exiger(false);
    return coalesce((
        select jsonb_agg(jsonb_build_object(
            'id', s.id, 'nom', s.nom, 'statut', s.statut, 'note', s.note,
            'lignes', coalesce(st.n, 0), 'lignes_lues', s.lignes_lues,
            'doublons_rejetes', s.doublons_rejetes, 'invalides', s.invalides,
            'created_at', s.created_at) order by s.nom)
        from trieur_data.leads_sources s
        left join (select source_id, sum(n) n from trieur_data.leads_stats group by 1) st on st.source_id = s.id
    ), '[]'::jsonb);
end;
$$;

-- Lignes par département (après exclusion de sources) : instantané et exact
create or replace function trieur_data.leads_compter(p_depts smallint[], p_exclues smallint[]) returns jsonb
language plpgsql stable security definer set search_path = trieur_data as $$
begin
    perform trieur_data.leads_exiger(false);
    return coalesce((
        select jsonb_agg(jsonb_build_object('dept', dept, 'libelle', trieur_data.leads_dept_libelle(dept), 'n', n) order by dept)
        from (select dept, sum(n) n from trieur_data.leads_stats
              where (p_depts is null or dept = any(p_depts))
                and (p_exclues is null or source_id <> all(p_exclues))
              group by dept having sum(n) > 0) t
    ), '[]'::jsonb);
end;
$$;

-- Tâche : création / progression / fin / annulation / liste
create or replace function trieur_data.leads_job_creer(p_kind text, p_source smallint, p_filename text,
                                                       p_total bigint, p_params jsonb) returns jsonb
language plpgsql security definer set search_path = trieur_data as $$
declare r trieur_data.leads_jobs;
begin
    perform trieur_data.leads_exiger(p_kind = 'import');
    insert into trieur_data.leads_jobs (kind, source_id, filename, lignes_total, params, created_by)
    values (p_kind, p_source, p_filename, p_total, p_params, auth.uid()) returning * into r;
    return to_jsonb(r);
end;
$$;

create or replace function trieur_data.leads_job_etat(p_job uuid, p_lues bigint default null, p_status text default null,
                                                      p_message text default null, p_inserees bigint default null,
                                                      p_params jsonb default null) returns jsonb
language plpgsql security definer set search_path = trieur_data as $$
declare r trieur_data.leads_jobs;
begin
    perform trieur_data.leads_exiger(false);
    update trieur_data.leads_jobs set
        lignes_lues = coalesce(p_lues, lignes_lues),
        inserees = coalesce(p_inserees, inserees),
        status = case when status = 'annule' then status else coalesce(p_status, status) end,
        message = coalesce(p_message, message),
        params = case when p_params is null then params else coalesce(params, '{}'::jsonb) || p_params end,
        updated_at = now()
    where id = p_job and (created_by = auth.uid() or trieur_data.is_super_admin())
    returning * into r;
    if not found then return null; end if;
    return to_jsonb(r);
end;
$$;

create or replace function trieur_data.leads_job_annuler(p_job uuid) returns jsonb
language plpgsql security definer set search_path = trieur_data as $$
declare r trieur_data.leads_jobs;
begin
    perform trieur_data.leads_exiger(false);
    update trieur_data.leads_jobs set status = 'annule', message = coalesce(message, 'Annulé par l''utilisateur'), updated_at = now()
    where id = p_job and status = 'en_cours' and (created_by = auth.uid() or trieur_data.is_super_admin())
    returning * into r;
    if not found then return null; end if;
    return to_jsonb(r);
end;
$$;

create or replace function trieur_data.leads_jobs_lister(p_kind text default null, p_limite int default 20) returns jsonb
language plpgsql stable security definer set search_path = trieur_data as $$
begin
    perform trieur_data.leads_exiger(false);
    return coalesce((select jsonb_agg(to_jsonb(j) - 'no' order by j.created_at desc)
        from (select * from trieur_data.leads_jobs
              where (p_kind is null or kind = p_kind) and (created_by = auth.uid() or trieur_data.is_super_admin())
              order by created_at desc limit greatest(1, least(coalesce(p_limite, 20), 100))) j), '[]'::jsonb);
end;
$$;

create or replace function trieur_data.leads_job_lire(p_job uuid) returns jsonb
language plpgsql stable security definer set search_path = trieur_data as $$
begin
    perform trieur_data.leads_exiger(false);
    return (select to_jsonb(j) - 'no' from trieur_data.leads_jobs j
            where j.id = p_job and (j.created_by = auth.uid() or trieur_data.is_super_admin()));
end;
$$;

create or replace function trieur_data.leads_doublons_lister(p_job uuid) returns jsonb
language plpgsql stable security definer set search_path = trieur_data as $$
begin
    perform trieur_data.leads_exiger(false);
    return coalesce((select jsonb_agg(jsonb_build_object(
            'dept', trieur_data.leads_dept_libelle(d.dept), 'cle', d.cle, 'nom', d.nom,
            'source', s.nom, 'source_existante', s2.nom) order by d.id)
        from trieur_data.leads_doublons_exemples d
        join trieur_data.leads_sources s on s.id = d.source_id
        left join trieur_data.leads_sources s2 on s2.id = d.source_existante
        where d.job_id = p_job), '[]'::jsonb);
end;
$$;

-- ---------------------------------------------------------------
-- Import d'un lot : normalise, dédoublonne (insert ... on conflict do nothing), compte
-- ---------------------------------------------------------------
-- p_rows : tableau JSON d'objets avec les clés nom, prenom, email, tel_mobile, tel_fixe,
-- adresse, cp, ville, civilite, naissance (texte brut). p_lues = lignes lues du fichier
-- pour ce lot (vides comprises) : la progression est écrite dans la MÊME transaction que
-- l'insertion, donc une coupure ne peut jamais la décaler (reprise sûre).
create or replace function trieur_data.leads_importer_lot(p_job uuid, p_source smallint, p_rows jsonb, p_lues bigint)
returns jsonb
language plpgsql security definer set search_path = trieur_data as $$
declare
    v_job trieur_data.leads_jobs;
    v_total int;
    v_valides int;
    v_ins int;
    v_max int;
    v_deja int;
begin
    perform trieur_data.leads_exiger(true);
    select * into v_job from trieur_data.leads_jobs where id = p_job and kind = 'import';
    if v_job.id is null then raise exception 'tache_inconnue'; end if;
    if v_job.status <> 'en_cours' then raise exception 'tache_%', v_job.status; end if;

    create temporary table if not exists pg_temp.leads_lot (
        dept smallint, cle bigint, tel_mobile bigint, tel_fixe bigint, naissance date, civilite smallint,
        nom text, prenom text, email text, adresse text, cp text, ville text, rang int
    ) on commit delete rows;
    truncate pg_temp.leads_lot;

    insert into pg_temp.leads_lot
    select dept, cle, tel_mobile, tel_fixe, naissance, civilite, nom, prenom, email, adresse, cp, ville,
           row_number() over (partition by dept, cle) rang
    from (
        select trieur_data.leads_dept(x.cp) dept,
               trieur_data.leads_cle(x.tel_mobile, x.tel_fixe, x.email) cle,
               trieur_data.leads_tel(x.tel_mobile) tel_mobile, trieur_data.leads_tel(x.tel_fixe) tel_fixe,
               trieur_data.leads_date(x.naissance) naissance, trieur_data.leads_civilite(x.civilite) civilite,
               nullif(btrim(x.nom), '') nom, nullif(btrim(x.prenom), '') prenom,
               trieur_data.leads_email(x.email) email, nullif(btrim(x.adresse), '') adresse,
               nullif(btrim(x.cp), '') cp, nullif(btrim(x.ville), '') ville
        from jsonb_to_recordset(p_rows) as x(nom text, prenom text, email text, tel_mobile text, tel_fixe text,
                                             adresse text, cp text, ville text, civilite text, naissance text)
    ) t
    where cle is not null;
    get diagnostics v_valides = row_count;
    v_total := jsonb_array_length(p_rows);

    with ins as (
        insert into trieur_data.leads (dept, cle, tel_mobile, tel_fixe, naissance, job_no, source_id, civilite,
                                       nom, prenom, email, adresse, cp, ville)
        select dept, cle, tel_mobile, tel_fixe, naissance, v_job.no, p_source, civilite, nom, prenom, email, adresse, cp, ville
        from pg_temp.leads_lot where rang = 1 order by dept, cle
        on conflict (dept, cle) do nothing
        returning dept
    ), g as (
        select dept, count(*) n from ins group by dept
    ), st as (
        insert into trieur_data.leads_stats (dept, source_id, n)
        select dept, p_source, n from g
        on conflict (dept, source_id) do update set n = trieur_data.leads_stats.n + excluded.n
        returning n
    )
    select coalesce(sum(n), 0) into v_ins from g;

    -- exemples de doublons : ceux qui existaient déjà dans un autre import
    select count(*) into v_deja from trieur_data.leads_doublons_exemples where job_id = p_job;
    select valeur::int into v_max from trieur_data.leads_reglages where cle = 'doublons_exemples_max';
    if v_deja < coalesce(v_max, 0) and v_ins < v_valides then
        insert into trieur_data.leads_doublons_exemples (job_id, dept, cle, nom, source_id, source_existante)
        select p_job, t.dept, t.cle, t.nom, p_source, l.source_id
        from pg_temp.leads_lot t
        join trieur_data.leads l on l.dept = t.dept and l.cle = t.cle and t.rang = 1 and l.job_no is distinct from v_job.no
        limit v_max - v_deja;
    end if;

    update trieur_data.leads_jobs set lignes_lues = lignes_lues + p_lues, inserees = inserees + v_ins,
        doublons = doublons + (v_total - (v_total - v_valides) - v_ins), invalides = invalides + (v_total - v_valides),
        updated_at = now()
    where id = p_job;
    update trieur_data.leads_sources set lignes_lues = lignes_lues + v_total,
        doublons_rejetes = doublons_rejetes + (v_valides - v_ins), invalides = invalides + (v_total - v_valides)
    where id = p_source;
    return jsonb_build_object('lues', v_total, 'inserees', v_ins, 'doublons', v_valides - v_ins, 'invalides', v_total - v_valides);
end;
$$;

-- ---------------------------------------------------------------
-- Lecture : filtres communs (départements, sources exclues, filtres par colonne)
-- ---------------------------------------------------------------
create or replace function trieur_data.leads_where(p_exclues smallint[], p_filters jsonb) returns text
language plpgsql immutable set search_path = trieur_data as $$
declare
    v text := 'true';
    v_col text; v_spec jsonb; v_op text; v_val text;
begin
    if p_exclues is not null and cardinality(p_exclues) > 0 then
        v := v || format(' and l.source_id <> all(%L::smallint[])', p_exclues);
    end if;
    for v_col, v_spec in select * from jsonb_each(coalesce(p_filters, '{}'::jsonb)) loop
        if v_col not in ('nom', 'prenom', 'email', 'adresse', 'cp', 'ville') then
            raise exception 'colonne_inconnue: %', v_col;
        end if;
        v_op := coalesce(v_spec->>'op', 'contient');
        v_val := lower(coalesce(v_spec->>'value', ''));
        v := v || case v_op
            when 'vide' then format(' and coalesce(l.%I, '''') = ''''', v_col)
            when 'non vide' then format(' and coalesce(l.%I, '''') <> ''''', v_col)
            when 'égal à' then format(' and lower(coalesce(l.%I, '''')) = %L', v_col, v_val)
            when 'ne contient pas' then format(' and position(%L in lower(coalesce(l.%I, ''''))) = 0', v_val, v_col)
            else format(' and position(%L in lower(coalesce(l.%I, ''''))) > 0', v_val, v_col) end;
    end loop;
    return v;
end;
$$;

-- Champ CSV : guillemets seulement si nécessaire
create or replace function trieur_data.leads_csv(p_val text, p_sep text) returns text
language sql immutable parallel safe as $$
    select case when p_val is null then ''
                when strpos(p_val, p_sep) > 0 or strpos(p_val, '"') > 0 or strpos(p_val, chr(10)) > 0 or strpos(p_val, chr(13)) > 0 then '"' || replace(p_val, '"', '""') || '"'
                else p_val end;
$$;

create or replace function trieur_data.leads_entete_csv() returns text
language sql stable security definer set search_path = trieur_data as $$
    select array_to_string(array['Département','Source','Civilité','Nom','Prénom','Email','Téléphone mobile',
        'Téléphone fixe','Adresse','CP','Ville','Date de naissance'], (select valeur from trieur_data.leads_reglages where cle = 'separateur_csv'));
$$;

-- LECTURE UNIQUE (aperçu, export, comptage) : parcourt les partitions des départements
-- demandés, par position physique (ctid) croissante, sans index. Étape = `pas_blocs` blocs.
-- Rend toujours `suite` (où reprendre) tant qu'il reste quelque chose à lire ; null = fini.
--   p_mode 'apercu' : lignes en JSON (au plus p_limite)
--   p_mode 'csv'    : lignes en texte CSV sans entête (au plus p_limite si donné)
--   p_mode 'compte' : nombre de lignes seulement
-- p_blocs_max borne le nombre de blocs lus par appel (le temps d'une requête est limité à 8 s).
create or replace function trieur_data.leads_lire(p_depts smallint[], p_exclues smallint[], p_filters jsonb,
        p_dept smallint default null, p_apres text default null, p_limite int default null,
        p_blocs_max int default null, p_mode text default 'apercu') returns jsonb
language plpgsql stable security definer set search_path = trieur_data as $$
declare
    v_pas int := (select valeur::int from trieur_data.leads_reglages where cle = 'pas_blocs');
    v_sep text := (select valeur from trieur_data.leads_reglages where cle = 'separateur_csv');
    v_pre text := (select valeur from trieur_data.leads_reglages where cle = 'prefixe_tel');
    v_budget int := (select valeur::int from trieur_data.leads_reglages where cle = 'budget_ms');
    v_t0 timestamptz := clock_timestamp();
    v_blocs_max int := coalesce(p_blocs_max, (select valeur::int from trieur_data.leads_reglages where cle = 'apercu_blocs_max'));
    v_where text := trieur_data.leads_where(p_exclues, p_filters);
    v_liste smallint[];
    v_d smallint := p_dept;
    v_pos tid := coalesce(p_apres, '(0,0)')::tid;
    v_nb bigint; v_b bigint; v_fin tid; v_part text;
    v_reste int := p_limite;
    v_lus int := 0; v_n bigint := 0; v_cnt int; v_last tid;
    v_json jsonb := '[]'::jsonb; v_csv text := ''; v_morceau text; v_chunk jsonb;
    v_suite jsonb := null;
    v_sel text;
begin
    perform trieur_data.leads_exiger(false);
    select array_agg(dept order by dept) into v_liste from (select distinct dept from trieur_data.leads_stats
        where n > 0 and (p_depts is null or dept = any(p_depts))) t;
    if v_liste is null then
        return jsonb_build_object('rows', v_json, 'csv', v_csv, 'n', 0, 'suite', null, 'blocs', 0);
    end if;
    if v_d is null then v_d := v_liste[1]; end if;
    -- un département redemandé qui n'existe plus : on passe au suivant
    if not (v_d = any(v_liste)) then
        select min(x) into v_d from unnest(v_liste) x where x > v_d;
        v_pos := '(0,0)'::tid;
        if v_d is null then return jsonb_build_object('rows', v_json, 'csv', v_csv, 'n', 0, 'suite', null, 'blocs', 0); end if;
    end if;

    loop
        v_part := trieur_data.leads_partition(v_d);
        v_nb := pg_relation_size(format('trieur_data.%I', v_part)::regclass) / current_setting('block_size')::int;
        v_b := (v_pos::text::point)[0];
        if v_b >= v_nb then
            select min(x) into v_d from unnest(v_liste) x where x > v_d;
            v_pos := '(0,0)'::tid;
            if v_d is null then v_suite := null; exit; end if;
            continue;
        end if;
        if v_lus >= v_blocs_max or (v_reste is not null and v_reste <= 0)
           or (v_lus > 0 and extract(epoch from clock_timestamp() - v_t0) * 1000 >= v_budget) then
            v_suite := jsonb_build_object('dept', v_d, 'apres', v_pos::text);
            exit;
        end if;
        v_fin := format('(%s,0)', least(v_b + v_pas, v_nb))::tid;
        v_sel := case p_mode
            when 'compte' then 'count(*)::int, null::text, null::tid, ''[]''::jsonb'
            when 'csv' then format($f$count(*)::int, string_agg(concat_ws(%L, %s), E'\n' order by s.curseur), max(s.curseur), '[]'::jsonb$f$,
                    v_sep, 'trieur_data.leads_csv(s.dept, %1$L), trieur_data.leads_csv(s.source, %1$L), trieur_data.leads_csv(s.civilite, %1$L), '
                    || 'trieur_data.leads_csv(s.nom, %1$L), trieur_data.leads_csv(s.prenom, %1$L), trieur_data.leads_csv(s.email, %1$L), '
                    || 'trieur_data.leads_csv(s.tel_mobile, %1$L), trieur_data.leads_csv(s.tel_fixe, %1$L), trieur_data.leads_csv(s.adresse, %1$L), '
                    || 'trieur_data.leads_csv(s.cp, %1$L), trieur_data.leads_csv(s.ville, %1$L), trieur_data.leads_csv(s.naissance, %1$L)')
            else 'count(*)::int, null::text, max(s.curseur), coalesce(jsonb_agg(to_jsonb(s) order by s.curseur), ''[]''::jsonb)' end;
        if p_mode = 'csv' then
            v_sel := replace(v_sel, '%1$L', quote_literal(v_sep));
        end if;
        execute format($q$
            select %s from (
                select l.ctid curseur, trieur_data.leads_dept_libelle(l.dept) dept, src.nom source,
                       case l.civilite when 1 then 'M' when 2 then 'Mme' end civilite, l.nom, l.prenom, l.email,
                       case when l.tel_mobile is not null then %L || l.tel_mobile::text end tel_mobile,
                       case when l.tel_fixe is not null then %L || l.tel_fixe::text end tel_fixe,
                       l.adresse, l.cp, l.ville, l.naissance::text naissance
                from trieur_data.%I l join trieur_data.leads_sources src on src.id = l.source_id
                where l.dept = %s and l.ctid > %L::tid and l.ctid < %L::tid and %s
                order by l.ctid %s) s
        $q$, v_sel, v_pre, v_pre, v_part, v_d, v_pos::text, v_fin::text, v_where,
             case when v_reste is not null then 'limit ' || v_reste else '' end)
        into v_cnt, v_morceau, v_last, v_chunk;
        v_n := v_n + v_cnt;
        if p_mode = 'csv' and v_morceau is not null then v_csv := v_csv || case when v_csv = '' then '' else E'\n' end || v_morceau; end if;
        if p_mode = 'apercu' then v_json := v_json || v_chunk; end if;
        v_lus := v_lus + least(v_pas, greatest(v_nb - v_b, 0))::int;
        if v_reste is not null then
            v_reste := v_reste - v_cnt;
            if v_reste <= 0 and v_last is not null then v_pos := v_last; continue; end if;
        end if;
        v_pos := v_fin;
    end loop;
    return jsonb_build_object('rows', v_json, 'csv', v_csv, 'n', v_n, 'suite', v_suite, 'blocs', v_lus);
end;
$$;

-- Total de blocs à lire pour des départements donnés (barre de progression de l'export)
create or replace function trieur_data.leads_blocs(p_depts smallint[]) returns bigint
language plpgsql stable security definer set search_path = trieur_data as $$
declare v_t bigint := 0; d smallint;
begin
    perform trieur_data.leads_exiger(false);
    for d in select distinct dept from trieur_data.leads_stats where n > 0 and (p_depts is null or dept = any(p_depts)) loop
        v_t := v_t + pg_relation_size(format('trieur_data.%I', trieur_data.leads_partition(d))::regclass) / current_setting('block_size')::int;
    end loop;
    return v_t;
end;
$$;

