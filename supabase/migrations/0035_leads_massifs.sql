-- Département -> nom de la partition ; créées ici, une fois (1..95 sauf 20, Corse 201/202,
-- DOM 971..976) + une partition "autres" pour tout le reste (étranger, code postal absent).
do $$
declare d int;
begin
    for d in select x from generate_series(1, 95) x where x <> 20
             union all select unnest(array[201, 202, 971, 972, 973, 974, 975, 976]) order by 1 loop
        execute format('create table if not exists trieur_data.%I partition of trieur_data.leads for values in (%s)',
                       'leads_p' || lpad(d::text, 3, '0'), d);
    end loop;
    execute 'create table if not exists trieur_data.leads_p_autres partition of trieur_data.leads default';
end $$;

alter table trieur_data.leads_reglages enable row level security;
alter table trieur_data.leads_sources enable row level security;
alter table trieur_data.leads_stats enable row level security;
alter table trieur_data.leads_jobs enable row level security;
alter table trieur_data.leads_doublons_exemples enable row level security;
alter table trieur_data.leads enable row level security;
-- aucune politique : personne ne lit ni n'écrit ces tables directement ; tout passe par
-- les fonctions ci-dessous (security definer), qui vérifient l'appartenance à Leads.
revoke all on trieur_data.leads_reglages, trieur_data.leads_sources, trieur_data.leads_stats,
    trieur_data.leads_jobs, trieur_data.leads_doublons_exemples, trieur_data.leads from public, anon, authenticated;

